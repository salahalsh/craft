def get_module_bits(module: str) -> List[BitDefinition]:
    """Get all bit definitions for a specific module."""
    start, end = MODULE_RANGES[module]
    return [b for b in CRAFT_SCHEMA if start <= b.position <= end]


def get_bits_by_source(source: str) -> List[BitDefinition]:
    """Get all bit definitions that depend on a specific data source."""
    return [b for b in CRAFT_SCHEMA if b.data_source == source]


def get_bits_by_category(category: str) -> List[BitDefinition]:
    """Get all bit definitions in a specific sub-category."""
    return [b for b in CRAFT_SCHEMA if b.category == category]


def describe_active_bits(vector, mode='binary') -> List[Dict]:
    """Return human-readable descriptions of all active (ON) bits."""
    active = []
    for i, val in enumerate(vector):
        if (mode == 'binary' and val == 1) or (mode == 'fuzzy' and val > 0.0):
            bit = CRAFT_BIT_INDEX[i]
            active.append({
                'position': i,
                'module': bit.module,
                'name': bit.name,
                'description': bit.description,
                'category': bit.category,
                'confidence': float(val) if mode == 'fuzzy' else 1.0,
                'source': bit.data_source,
                'biological_basis': bit.biological_basis,
            })
    return active
