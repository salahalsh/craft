"""
CRAFT Fingerprint Schema - 256-Bit Bio-Context Fingerprint Definition

Every bit position is explicitly defined, biologically justified, and traceable
to a public database source. The schema is divided into 4 modules of 64 bits each:

  Module A [0-63]:   Membrane Topology & Localization
  Module B [64-127]:  Signal Transduction Mechanism
  Module C [128-191]: Binding Pocket Character
  Module D [192-255]: Endogenous Ligand Type

Each module has 4 sub-blocks of 16 bits for hierarchical organization.

Data sources:
  - uniprot:  UniProt REST API (subcellular localization, topology, keywords)
  - iuphar:   IUPHAR/BPS Guide to Pharmacology (target class, signaling, ligands)
  - chembl:   ChEMBL (target classification, bioactivity context)
  - pocket:   Binding pocket analysis (PDB-based or class-based fallback)
  - derived:  Inferred from combination of sources

Author: Dr. Salah - Insilico Sigma Lab
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional


@dataclass(frozen=True)
class BitDefinition:
    """Definition of a single bit position in the CRAFT fingerprint."""
    position: int           # 0-255 absolute position
    module: str             # 'A', 'B', 'C', 'D'
    name: str               # Machine-readable short name (unique)
    description: str        # Human-readable description
    data_source: str        # 'uniprot', 'iuphar', 'chembl', 'pocket', 'derived'
    category: str           # Sub-category within module
    biological_basis: str = ''  # Brief justification for inclusion


